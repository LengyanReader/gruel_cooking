def lcard(lang):
    ready = lang.get("status") == "active"
    stat = "ready" if ready else "planned"
    stat_zh, stat_en = ("学习入口" if ready else "建设中"), ("Enter" if ready else "Planned")
    glyph = f'<span class="glyph">{e(lang["glyph"])}</span>'
    name_zh = f'<span class="name" data-zh>{e(lang["name_zh"])}</span>'
    name_en = f'<span class="name" data-en>{e(lang["name_en"])}</span>'
    summary = (f'<span class="summary" data-zh>{e(lang["summary_zh"])}</span>'
               f'<span class="summary" data-en>{e(lang["summary_en"])}</span>')
    stat_tag = (f'<span class="status {stat}" data-zh>{stat_zh}</span>'
                f'<span class="status {stat}" data-en>{stat_en}</span>')
    enter = "" if not ready else (
        f'<a class="enter" href="{e(lang["href"])}" data-zh>进入学习 &rarr;</a>'
        f'<a class="enter" href="{e(lang["href"])}" data-en>Enter &rarr;</a>'
    )
    href = e(lang["href"]) if ready else "#future"
    return (f'<a class="card card-{stat}" href="{href}">{glyph}{name_zh}{name_en}<br>'
            f'<span class="iso">{e(lang["iso"])}</span>{summary}{stat_tag}{enter}</a>')


def render_hub_cards(registry, prose):
    langs = registry["languages"]
    active = [x for x in langs if x.get("status") == "active"]
    planned = [x for x in langs if x.get("status") != "active"]
    cards = "".join(lcard(x) for x in active + planned)
    return prose + f'<section class="cards" aria-label="languages">{cards}</section>'


