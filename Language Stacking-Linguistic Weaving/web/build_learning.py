def pitch_svg(seq, w=148, h=56):
    """四型高低调示意图（自绘 SVG，离线可用）。seq 如 'LHHL'。"""
    hi, lo = 15, 41
    n = max(len(seq), 2)
    step = (w - 16) / (n - 1)
    pts = [(round(8 + i * step, 1), hi if c == "H" else lo) for i, c in enumerate(seq)]
    poly = " ".join(f"{x},{y}" for x, y in pts)
    dots = "".join(f'<circle cx="{x}" cy="{y}" r="3.1"/>' for x, y in pts)
    marks = ""
    for i in range(1, len(seq)):
        if seq[i - 1] == "H" and seq[i] == "L":
            mx = (pts[i - 1][0] + pts[i][0]) / 2
            marks += (f'<line x1="{mx}" y1="{hi}" x2="{mx}" y2="{lo}" '
                      'stroke="#c0705f" stroke-width="1.3" stroke-dasharray="3 3"/>')
    return (f'<svg class="pitch-svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            'role="img" aria-hidden="true">'
            f'<polyline points="{poly}" fill="none" stroke="#C9A465" stroke-width="2.3" '
            'stroke-linecap="round" stroke-linejoin="round"/>'
            f'{marks}<g fill="#8a6f3d">{dots}</g></svg>')


