def kana_origin_line(c):
    """tooltip 内的字源行（第四旋·源 在每一格上留下的回望线索）。"""
    if not (c.get("origin") or c.get("origin_k")):
        return ""
    o = e(c.get("origin", ""))
    ok = e(c.get("origin_k", ""))
    return (f'<span class="kana-origin"><span data-zh>字源 {o} / {ok}</span>'
            f'<span data-en>origin {o} / {ok}</span></span>')


