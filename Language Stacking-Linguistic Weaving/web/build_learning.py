def render_prose(md_body):
    """多段双语 markdown → HTML。无标记段 = 共享段（zh/en 双份）。"""
    pattern = re.compile(r"^\s*<!--\s*(zh|en)\s*-->\s*$", re.M)
    parts = pattern.split(md_body)
    out = []
    if parts[0].strip():
        h = _render_md(parts[0])
        out.append(f'<div data-both="1"><div data-bit="zh">{h}</div><div data-bit="en">{h}</div></div>')
    for i in range(1, len(parts), 2):
        bit, chunk = parts[i], parts[i + 1]
        if not chunk.strip():
            continue
        out.append(f'<div data-both="1"><div data-bit="{bit}">{_render_md(chunk)}</div></div>')
    return "".join(out)


def _render_md(md_text):
    MD.reset()
    return MD.convert(md_text).strip()


