def crumbs(*segments):
    """(label, href|None, label, href|None, ...) 扁平行参 → 面包屑 HTML，以 › 分隔"""
    parts = []
    for i in range(0, len(segments) - 1, 2):
        label, href = segments[i], segments[i + 1]
        if href:
            parts.append(f'<a href="{e(href)}">{e(label)}</a>')
        else:
            parts.append(f"<span>{e(label)}</span>")
    return " &rsaquo; ".join(parts)


