def kana_index_html(data):
    """把每个假名的四旋信息（形音/词义/例句/文化/字源/分层）压成 JSON 索引。

    供前端弹窗一次性取用，避免点击跳转；以 data JSON 为单一数据源。
    """
    idx = {}

    for row in data["chart"]["rows"]:
        for c in row["cells"]:
            if c.get("void"):
                continue
            d = idx.setdefault(c["h"], {"h": c["h"]})
            for k in ("kat", "r", "note_zh", "note_en", "origin", "origin_k"):
                if c.get(k):
                    d[k] = c[k]
    n = data["chart"].get("n")
    if isinstance(n, dict):
        d = idx.setdefault(n["h"], {"h": n["h"]})
        for k in ("kat", "r", "note_zh", "note_en", "origin", "origin_k"):
            if n.get(k):
                d[k] = n[k]

    keys = ("kat", "r", "kanji", "kana", "rom", "meaning_zh", "meaning_en",
            "sent", "sent_rom", "tr_zh", "tr_en", "sea_zh", "sea_en",
            "art_zh", "art_en", "ref_zh", "ref_en", "layer_zh", "layer_en")
    for v in data["vocab"]:
        d = idx.setdefault(v["h"], {"h": v["h"]})
        for k in keys:
            if v.get(k):
                d[k] = v[k]

    payload = json.dumps(idx, ensure_ascii=False)
    payload = (payload.replace("<", "\\u003c")
                      .replace(">", "\\u003e")
                      .replace("&", "\\u0026"))
    return f'<script type="application/json" id="kana-index">{payload}</script>'


