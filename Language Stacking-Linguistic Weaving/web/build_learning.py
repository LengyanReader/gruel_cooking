# ── 工具 ───────────────────────────────────────────────────────
def e(s):
    return html.escape(str(s), quote=True)


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def parse_frontmatter(text):
    """顶部 ---json ... --- frontmatter → (dict|None, body)"""
    m = re.match(r"^---json\s*\n(.*?)\n---\s*\n?", text, re.S)
    if not m:
        return None, text
    return json.loads(m.group(1)), text[m.end():]


def strip_h1(md):
    """去掉第一个 '# ' 标题行(页面体现为 hero, 不重复占 h1)"""
    return re.sub(r"^# .*\n+", "", md, count=1)


def render_prose(md_body):
    """多段双语 markdown → HTML。无标记段 = 共享段（zh/en 双份）。"""
    pattern = re.compile(r"^\s*<!--\s*(zh|en)\s*-->\s*$", re.M)
    parts = pattern.split(md_body)
    out = []
    if parts[0].strip():
        h = _render_md(parts[0])
        out.append(f'<div data-both="1"><div data-bit="zh">{h}</div><div data-bit="en">{h}</div></div>')
    for i in range(1, len(parts), 2):
        bit, chunk = parts[i], parts[i + 1]
        if not chunk.strip():
            continue
        out.append(f'<div data-both="1"><div data-bit="{bit}">{_render_md(chunk)}</div></div>')
    return "".join(out)


def _render_md(md_text):
    MD.reset()
    return MD.convert(md_text).strip()


def zh_en(text_zh, text_en):
    return f'<span data-zh>{e(text_zh)}</span><span data-en>{e(text_en)}</span>'


