def sync_sqlite(registry, langs_modules, db_path=None):
    import sqlite3
    db_path = db_path or os.path.join(DATA, "learning.db")
    os.makedirs(os.path.dirname(db_path), exist_ok=True)
    con = sqlite3.connect(db_path)
    cur = con.cursor()
    cur.execute("""CREATE TABLE IF NOT EXISTS meta(
        key TEXT PRIMARY KEY, value TEXT)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS languages(
        id TEXT PRIMARY KEY, glyph TEXT, name_zh TEXT, name_en TEXT,
        iso TEXT, status TEXT, summary_zh TEXT, summary_en TEXT, href TEXT)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS modules(
        id TEXT, lang TEXT, href TEXT, status TEXT,
        name_zh TEXT, name_en TEXT, PRIMARY KEY(id, lang))""")
    cur.execute("""CREATE TABLE IF NOT EXISTS chart_cells(
        lang TEXT, module TEXT, row TEXT, col INTEGER, h TEXT, kata TEXT,
        roma TEXT, note TEXT, PRIMARY KEY(lang, module, row, col))""")
    cur.execute("""CREATE TABLE IF NOT EXISTS vocab(
        lang TEXT, module TEXT, id TEXT, hira TEXT, kata TEXT, roma TEXT,
        kanji TEXT, kana TEXT, meaning_zh TEXT, meaning_en TEXT,
        sentence TEXT, sent_rom TEXT, tr_zh TEXT, tr_en TEXT,
        PRIMARY KEY(lang, module, id))""")
    cur.execute("""CREATE TABLE IF NOT EXISTS accent_types(
        id TEXT PRIMARY KEY, lang TEXT, module TEXT, num INTEGER,
        name_zh TEXT, name_en TEXT, seq TEXT, zh TEXT, en TEXT)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS mpairs(
        id TEXT PRIMARY KEY, lang TEXT, module TEXT, kind TEXT, idx INTEGER,
        a_kana TEXT, a_rom TEXT, b_kana TEXT, b_rom TEXT, c_kana TEXT, c_rom TEXT,
        zh TEXT, en TEXT, src TEXT)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS media_links(
        id TEXT PRIMARY KEY, lang TEXT, module TEXT, kind TEXT,
        title_zh TEXT, title_en TEXT, url TEXT, note_zh TEXT, note_en TEXT)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS concepts(
        id TEXT PRIMARY KEY, name_zh TEXT, name_en TEXT, probe INTEGER DEFAULT 0)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS concept_terms(
        concept TEXT, lang TEXT, word TEXT, roma TEXT,
        PRIMARY KEY(concept, lang))""")
    cur.execute("""CREATE TABLE IF NOT EXISTS scripts(
        id TEXT PRIMARY KEY, name_zh TEXT, name_en TEXT,
        note_zh TEXT, note_en TEXT, langs TEXT)""")
    cur.execute("""CREATE TABLE IF NOT EXISTS threads(
        id TEXT PRIMARY KEY, kind TEXT, from_ref TEXT, to_ref TEXT,
        note_zh TEXT, note_en TEXT)""")
    cur.execute("DELETE FROM languages")
    cur.execute("DELETE FROM modules")
    cur.execute("DELETE FROM chart_cells")
    cur.execute("DELETE FROM vocab")
    cur.execute("DELETE FROM accent_types")
    cur.execute("DELETE FROM mpairs")
    cur.execute("DELETE FROM media_links")
    _sync_glossary(cur)
    cur.executemany("INSERT INTO languages VALUES(:id,:glyph,:name_zh,:name_en,:iso,:status,:summary_zh,:summary_en,:href)",
                    [{"id": l["id"], **{k: l.get(k, "") for k in ("glyph", "name_zh", "name_en", "iso", "status", "summary_zh", "summary_en", "href")}}
                     for l in registry["languages"]])
    for lang_id, modules in langs_modules.items():
        for m in modules:
            cur.execute("INSERT INTO modules VALUES(?,?,?,?,?,?)",
                        (m["id"], lang_id, m.get("href", ""), m.get("status", "planned"),
                         m.get("name_zh", ""), m.get("name_en", "")))
            jpath = os.path.join(DATA, lang_id, f"{m['id']}.json")
            if os.path.exists(jpath):
                data = json.loads(read(jpath))
                _sync_chart(cur, lang_id, m["id"], data)
                _sync_vocab(cur, lang_id, m["id"], data)
                _sync_prosody(cur, lang_id, m["id"], data)
                _sync_media(cur, lang_id, m["id"], data)
    cur.execute("INSERT OR REPLACE INTO meta VALUES('schema_version','1')")
    cur.execute("INSERT OR REPLACE INTO meta VALUES('builder','build_learning.py')")
    con.commit()
    con.close()
    print(f"[db] 学习库索引已同步: {db_path}")


def _sync_glossary(cur):
    """织网库 Core Glossary → concepts/concept_terms/scripts/threads 表。"""
    g = load_core_glossary()
    for c in g.get("concepts", []):
        cur.execute("INSERT OR REPLACE INTO concepts VALUES(?,?,?,0)",
                    (c["id"], c.get("name_zh", ""), c.get("name_en", "")))
        for lang, t in (c.get("terms") or {}).items():
            cur.execute("INSERT OR REPLACE INTO concept_terms VALUES(?,?,?,?)",
                        (c["id"], lang, t.get("word", ""), t.get("roma", "")))
    for s in g.get("scripts", []):
        cur.execute("INSERT OR REPLACE INTO scripts VALUES(?,?,?,?,?,?)",
                    (s["id"], s.get("name_zh", ""), s.get("name_en", ""),
                     s.get("note_zh", ""), s.get("note_en", ""),
                     ",".join(s.get("langs", []))))
    for t in g.get("threads", []):
        cur.execute("INSERT OR REPLACE INTO threads VALUES(?,?,?,?,?,?)",
                    (t["id"], t["kind"], t["from"], t["to"],
                     t.get("note_zh", ""), t.get("note_en", "")))


