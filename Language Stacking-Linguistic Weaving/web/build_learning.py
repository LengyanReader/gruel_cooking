def langs_with_modules():
    """iterator: (entry, meta, body_md) 仅 active 语种"""
    registry, _ = load_registry()
    for entry in registry["languages"]:
        if entry.get("status") != "active":
            continue
        meta, body = parse_frontmatter(read(os.path.join(LANG, entry["id"], "README.md")))
        yield entry, meta, body


def build():
    registry, hub_body_md = load_registry()
    active = [x for x in registry["languages"] if x.get("status") == "active"]
    if not active:
        raise SystemExit("[build] 注册表无 active 语种，无法构建")
    hub_prose = render_prose(strip_h1(hub_body_md))

    pages = {os.path.join(OUT, "index.html"): render_hub(registry, hub_prose, active[0]["id"])}

    for entry, meta, body in langs_with_modules():
        modules = meta.get("modules", [])
        ready = [m for m in modules if m.get("status") == "ready"]
        base = os.path.join(OUT, entry["id"])
        pages[os.path.join(base, "index.html")] = render_lang_index(entry, meta, body,
                                                                    ready[0] if ready else None)
        for m in ready:
            md_path = os.path.join(LANG, entry["id"], f"{m['id']}.md")
            if os.path.exists(md_path):
                pages[os.path.join(base, f"{m['id']}.html")] = render_module_page(
                    entry, m, read(md_path))
    if glossary_ready():
        pages[os.path.join(OUT, "glossary", "index.html")] = render_glossary_page()
    return pages


