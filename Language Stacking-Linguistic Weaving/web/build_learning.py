def validate_glossary():
    """织网库 Core Glossary 结构校验（概念权威，绝不静默出错）。"""
    errors = []
    if not os.path.exists(GLOSSARY_JSON):
        errors.append("缺 core_glossary.json（织网库概念权威）")
        return errors
    try:
        g = json.loads(read(GLOSSARY_JSON))
    except ValueError as exc:
        errors.append(f"core_glossary.json 解析失败: {exc}")
        return errors
    langs = g.get("languages") or []
    if len(langs) < 2:
        errors.append("core_glossary languages 列表缺失或过短")
        return errors
    ids = []
    for c in g.get("concepts", []):
        cid = c.get("id")
        if not cid:
            errors.append("概念缺 id")
            continue
        ids.append(cid)
        for field in ("name_zh", "name_en"):
            if not c.get(field):
                errors.append(f"[{cid}] 缺字段 {field}")
        terms = c.get("terms") or {}
        missing = [l for l in langs if l not in terms]
        if missing:
            errors.append(f"[{cid}] 缺语种词位: {missing}")
        for lang, t in terms.items():
            if not isinstance(t, dict) or "word" not in t:
                errors.append(f"[{cid}/{lang}] 词位缺 word")
            if not isinstance(t, dict) or "roma" not in t:
                errors.append(f"[{cid}/{lang}] 词位缺 roma 键")
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        errors.append(f"概念 id 重复: {dupes}")
    lang_set = set(langs)
    for s in g.get("scripts", []):
        if not s.get("id"):
            errors.append("script 缺 id")
            continue
        bad = [l for l in s.get("langs", []) if l not in lang_set]
        if bad:
            errors.append(f"[script {s['id']}] 语言不在注册: {bad}")
    for t in g.get("threads", []):
        if t.get("kind") not in THREAD_KIND:
            errors.append(f"[thread {t.get('id')}] kind 非法: {t.get('kind')}")
        for ref in (t.get("from"), t.get("to")):
            if not ref or not (ref.startswith("root:") or ":" in ref):
                errors.append(f"[thread {t.get('id')}] 引用格式非法: {ref!r}")
    if not g.get("meta", {}).get("review"):
        errors.append("core_glossary 缺 meta.review（审校状态必须声明）")
    return errors


def validate_sources():
    """返回错误消息列表（空 = 通过）。节奏：绝不静默出错。"""
    errors = []

    registry, hub_body = load_registry()
    langs = registry["languages"]
    if not langs:
        errors.append("hub frontmatter 缺 languages 列表")

    ids = [l.get("id") for l in langs if l.get("id")]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        errors.append(f"语种 id 重复: {dupes}")

    for l in langs:
        lid = l.get("id")
        for field in ("name_zh", "name_en", "iso", "glyph", "summary_zh", "summary_en"):
            if not l.get(field):
                errors.append(f"[{lid or '?'}] 缺字段 {field}")
        if l.get("status") == "active":
            if not l.get("href"):
                errors.append(f"[{lid}] active 语种缺 href")
            # active 语种必有 README；planned 语种不允许出现学习页文件
            readme = os.path.join(LANG, lid, "README.md")
            if not os.path.exists(readme):
                errors.append(f"[{lid}] active 语种缺 {lid}/README.md")
            meta, body = parse_frontmatter(read(readme))
            if meta is None:
                errors.append(f"[{lid}] README.md 无 frontmatter")
                continue
            modules = meta.get("modules", [])
            m_ids = [m.get("id") for m in modules]
            m_dupes = sorted({i for i in m_ids if m_ids.count(i) > 1})
            if m_dupes:
                errors.append(f"[{lid}] 模块 id 重复: {m_dupes}")
            for m in modules:
                for field in ("name_zh", "name_en", "desc_zh", "desc_en"):
                    if not m.get(field):
                        errors.append(f"[{lid}/{m.get('id')}] 缺模块字段 {field}")
                if m.get("status") == "ready":
                    if m.get("href") != f"{m['id']}.html":
                        errors.append(f"[{lid}/{m['id']}] ready 模块 href 应为 {m['id']}.html")
                    mdp = os.path.join(LANG, lid, f"{m['id']}.md")
                    if not os.path.exists(mdp):
                        errors.append(f"[{lid}/{m['id']}] ready 模块缺页面源 {m['id']}.md")
                    else:
                        validate_md_bilingual(mdp, errors, lid, m["id"])
                    jpath = os.path.join(DATA, lid, f"{m['id']}.json")
                    if os.path.exists(jpath):
                        validate_module_json(jpath, errors, lid, m["id"])
                else:  # planned
                    if m.get("href") not in (None, "", "#future"):
                        errors.append(f"[{lid}/{m['id']}] planned 模块不应有实际 href")
            if body and not body.strip():
                errors.append(f"[{lid}] README 正文为空")
    errors += validate_glossary()
    if not os.path.exists(GLOSSARY_MD):
        errors.append("缺 glossary.md（织网库散文页源）")
    else:
        validate_md_bilingual(GLOSSARY_MD, errors, "glossary", "index")
    return errors


def validate_md_bilingual(path, errors, lid, mid):
    text = read(path)
    zh = len(re.findall(r"^\s*<!--\s*zh\s*-->", text, re.M))
    en = len(re.findall(r"^\s*<!--\s*en\s*-->", text, re.M))
    if zh != en:
        errors.append(f"[{lid}/{mid}] 双语标记不平衡 zh={zh} en={en}")
    if strip_h1(text) == text and not re.match(r"^#\s+.+", text):
        errors.append(f"[{lid}/{mid}] 缺 H1 标题行")


def validate_module_json(path, errors, lid, mid):
    try:
        data = json.loads(read(path))
    except ValueError as exc:
        errors.append(f"[{lid}/{mid}] JSON 解析失败: {exc}")
        return
    kind = (data.get("meta") or {}).get("kind")
    if kind and kind not in KIND_VIEWS:
        errors.append(f"[{lid}/{mid}] JSON meta.kind={kind} 未注册渲染视图(KIND_VIEWS)，页面将只有 prose")
    if "chart" in data:
        chart = data["chart"]
        for ri, row in enumerate(chart.get("rows", [])):
            for ci, c in enumerate(row.get("cells", [])):
                keys = set(c)
                if c.get("void"):
                    if keys - {"void"}:
                        errors.append(f"[{lid}/{mid}] 第{ri}行{ci}列 void 单元携带多余键 {sorted(keys - {'void'})}")
                    continue
                for field in ("h", "kat", "r"):
                    if not c.get(field):
                        errors.append(f"[{lid}/{mid}] 第{ri}行{ci}列缺字段 {field}")
    if "vocab" in data:
        for i, v in enumerate(data["vocab"]):
            for field in ("h", "kanji", "kana", "rom", "meaning_zh", "meaning_en", "sent", "sent_rom", "tr_zh", "tr_en", "r", "kat"):
                if not v.get(field):
                    errors.append(f"[{lid}/{mid}] 词表第{i}条缺字段 {field}")


# ── 产物校验 ───────────────────────────────────────────────────
def check_outputs(pages):
    ok = True
    expected = set(pages.keys())
    for path, text in pages.items():
        if not os.path.exists(path):
            print(f"[check] MISSING {path}")
            ok = False
            continue
        needles = ["data-bit"]
        rel = os.path.relpath(path, OUT)
        if "data-bit" not in text:
            ok = False
            print(f"[check] {rel} 缺 data-bit")
        for tag in ("div", "table", "span", "a", "section"):
            opens = len(re.findall(r"<" + tag + r"(?!\w)", text))
            closes = len(re.findall(r"</" + tag + r"\s*>", text))
            delta = opens - closes
            if delta:
                print(f"[check] {rel} 标签<{tag}>不平衡 ±{delta}")
                ok = False
        if len(text) < 2000:
            print(f"[check] {rel} 内容过短")
            ok = False
    # 陈旧产物检测：OUT 下存在但本次未声明的 .html
    stale = set()
    for root, _dirs, files in os.walk(OUT):
        for fn in files:
            if fn.endswith(".html"):
                full = os.path.join(root, fn)
                if full not in expected:
                    stale.add(full)
    if stale:
        ok = False
        for s in sorted(stale):
            print(f"[check] 陈旧产物(不在本次构建): {s}")
    return ok


